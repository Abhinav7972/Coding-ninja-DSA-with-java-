

public class Char_array {
  public static void main(String[] args) {
    char ch [] = {'a','b','c','d'};
    int i [] = {1,2,3,4}; 
     
    System.out.println(i); //integer array return  memory address
    System.out.println(ch); //character array return array value
    System.out.println(Character.toUpperCase(ch[0])); // string method on array
    System.out.println(ch.toString()); // to get memory address of char array we  convert it to string 
    



    
  }
}
