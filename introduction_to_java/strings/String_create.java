public class String_create {
 public static void main(String[] args) {
   String s1 = "Alpha";
   String s2 = "Man"; 

   String s3 = s1.concat(s2); //concat method of string 

   System.out.println(s3); //printing concated strings
   System.out.println(s1.toUpperCase()); //converting string to upper case 
   System.out.println(s1.charAt(2)); //return character at particular place 
   
 }
}
